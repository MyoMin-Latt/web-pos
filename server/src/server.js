import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import { connectDB, isDbReady } from './config/db.js';
import { errorHandler, notFound } from './middleware/errorHandler.js';
import userRoutes from './features/users/userRoutes.js';
import itemRoutes from './features/items/itemRoutes.js';
import customerRoutes from './features/customers/customerRoutes.js';
import invoiceRoutes from './features/invoices/invoiceRoutes.js';
const app = express();
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173' }));
app.use(express.json());
app.get('/api/health', (req, res) => res.json({ ok: true, mode: isDbReady() ? 'mongodb' : 'demo-memory', mongoConnected: isDbReady(), time: new Date().toISOString() }));
app.use('/api/users', userRoutes);
app.use('/api/items', itemRoutes);
app.use('/api/customers', customerRoutes);
app.use('/api/invoices', invoiceRoutes);
app.use(notFound);
app.use(errorHandler);
const PORT = process.env.PORT || 5031;
await connectDB(process.env.MONGO_URI);
app.listen(PORT, () => console.log(`[Server] Listening on http://localhost:${PORT} (mode: ${isDbReady() ? 'mongodb' : 'demo-memory'})`));
